-- Shared by all broker apps (one database, every row tagged with its broker account).

-- One row per configured account (broker + the name used in secrets.properties).
create table broker_account (
    id                bigint generated by default as identity primary key,
    broker            varchar(30)   not null,
    name              varchar(50)   not null,
    user_id           varchar(50),
    user_name         varchar(100),
    access_token      varchar(1000),             -- AES-GCM encrypted
    token_expires_at  timestamp with time zone,
    last_sync_at      timestamp with time zone,
    last_sync_ok      boolean,
    last_sync_message varchar(1000),
    constraint uq_broker_account unique (broker, name)
);

-- Snapshots: every sync adds rows stamped with taken_at. Old ones are deleted after sync.retention-days.
create table funds_snapshot (
    id             bigint generated by default as identity primary key,
    account_id     bigint not null references broker_account (id) on delete cascade,
    taken_at       timestamp with time zone not null,
    segment        varchar(20) not null,
    available_cash numeric(18, 2),
    used_margin    numeric(18, 2),
    net            numeric(18, 2)
);
create index ix_funds_account_time on funds_snapshot (account_id, taken_at);

create table holding_snapshot (
    id             bigint generated by default as identity primary key,
    account_id     bigint not null references broker_account (id) on delete cascade,
    taken_at       timestamp with time zone not null,
    symbol         varchar(50) not null,
    exchange       varchar(10) not null,
    isin           varchar(20),
    quantity       bigint not null,
    average_price  numeric(18, 4),
    last_price     numeric(18, 4),
    close_price    numeric(18, 4),
    pnl            numeric(18, 2),
    day_change_pct numeric(10, 4)
);
create index ix_holding_account_time on holding_snapshot (account_id, taken_at);

create table position_snapshot (
    id            bigint generated by default as identity primary key,
    account_id    bigint not null references broker_account (id) on delete cascade,
    taken_at      timestamp with time zone not null,
    symbol        varchar(50) not null,
    exchange      varchar(10) not null,
    product       varchar(10),
    quantity      bigint not null,
    average_price numeric(18, 4),
    last_price    numeric(18, 4),
    pnl           numeric(18, 2)
);
create index ix_position_account_time on position_snapshot (account_id, taken_at);

-- Orders: one row per broker order, updated on every sync. Kept forever.
create table broker_order (
    id              bigint generated by default as identity primary key,
    account_id      bigint not null references broker_account (id) on delete cascade,
    order_id        varchar(50) not null,
    symbol          varchar(50),
    exchange        varchar(10),
    side            varchar(4),
    order_type      varchar(10),
    product         varchar(10),
    quantity        bigint,
    price           numeric(18, 4),
    trigger_price   numeric(18, 4),
    status          varchar(30),
    filled_quantity bigint,
    average_price   numeric(18, 4),
    status_message  varchar(500),
    tag             varchar(30),
    placed_at       timestamp with time zone,
    updated_at      timestamp with time zone,
    placed_by_app   boolean not null default false,
    constraint uq_broker_order unique (account_id, order_id)
);
